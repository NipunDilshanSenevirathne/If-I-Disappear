"""Extraction quality by model, on the benchmark households (needs a key).

    GEMINI_API_KEY=... python -m evals.live_models [--models gemini-3.5-flash-lite,gemma-4-31b-it]

Runs the live extraction benchmark of evals/live_eval.py once per model, with that model
alone in the extractor's line, and writes evals/reports/live-models.md and .json. Each run
sends one request per benchmark source (29 on the four households). The default models are
the free tier's everyday workhorses; Gemini 3.8 Flash is left out by default because its
free allowance (20 requests a day) is smaller than one run.
"""

from __future__ import annotations

import argparse
import json
import os
import time
from datetime import UTC, datetime
from pathlib import Path

from .common import ROOT

REPORTS = ROOT / "evals" / "reports"
DEFAULT = "gemini-3.5-flash-lite,gemini-3.1-flash-lite,gemma-4-31b-it"


def run_one(model: str) -> dict:
    from app.ai import router
    from app.ai.quota import label
    from app.config import get_settings

    from .live_eval import live_section

    os.environ["AI_CHAIN_EXTRACTOR"] = model
    get_settings.cache_clear()
    router.cache.clear()  # never reuse another model's answers
    t0 = time.perf_counter()
    section = live_section(True)
    return {
        "model": model,
        "label": label(model),
        "minutes": round((time.perf_counter() - t0) / 60, 1),
        "metrics": [m.to_dict() for m in section.metrics],
        "details": section.details,
    }


def render(rep: dict) -> str:
    runs = rep["runs"]
    lines = [
        "# Extraction quality by model",
        "",
        f"Generated {rep['generated']} by `python -m evals.live_models`, on the four benchmark households (29 sources), "
        "through the app's real ingest workflow: the model extracts claims with quotes, code checks every quote. "
        "Each column is one model alone in the extractor's line (free tier). The hand-written claims and "
        "expected findings are the same ones the offline report uses.",
        "",
        "| Metric | Target | " + " | ".join(r["label"] for r in runs) + " |",
        "|---|---|" + "---|" * len(runs),
    ]
    names = [m["name"] for m in runs[0]["metrics"]] if runs else []
    for i, name in enumerate(names):
        target = runs[0]["metrics"][i].get("target") or ""
        cells = []
        for r in runs:
            m = r["metrics"][i]
            value = m.get("value") or "not run"
            cells.append(value + (" ✓" if m.get("status") == "pass" else (" ✗" if m.get("status") == "fail" else "")))
        lines.append(f"| {name} | {target} | " + " | ".join(cells) + " |")
    lines += ["", "| Model | Minutes for the run |", "|---|---:|"] + [f"| {r['label']} | {r['minutes']} |" for r in runs]
    for r in runs:
        lines += ["", f"**{r['label']}**", ""] + r["details"]
    lines += [
        "",
        "✓ meets the target, ✗ misses it. A miss is reported as it is; the household reviews every fact before it is used.",
        "This file is generated by `python -m evals.live_models`.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--models", default=DEFAULT)
    ap.add_argument("--out", type=Path, default=REPORTS)
    ap.add_argument("--merge", nargs="*", type=Path, default=[], help="live-models.json files from earlier runs to include first")
    args = ap.parse_args()
    runs = [r for path in args.merge for r in json.loads(path.read_text(encoding="utf-8"))["runs"]]
    if not args.models.strip() and runs:
        rep = {"generated": datetime.now(UTC).isoformat(timespec="seconds"), "runs": runs}
        args.out.mkdir(parents=True, exist_ok=True)
        (args.out / "live-models.json").write_text(json.dumps(rep, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        (args.out / "live-models.md").write_text(render(rep), encoding="utf-8")
        print(render(rep))
        return 0
    for model in [m.strip() for m in args.models.split(",") if m.strip()]:
        print(f"extracting with {model} ...", flush=True)
        runs.append(run_one(model))
        args.out.mkdir(parents=True, exist_ok=True)
        rep = {"generated": datetime.now(UTC).isoformat(timespec="seconds"), "runs": runs}
        (args.out / "live-models.json").write_text(json.dumps(rep, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        (args.out / "live-models.md").write_text(render(rep), encoding="utf-8")
    print(render(rep))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
